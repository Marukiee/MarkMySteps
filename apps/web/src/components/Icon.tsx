interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName;
  size?: number;
}

/**
 * Re-renders every icon when the skin changes, without a provider or a prop
 * threaded through 130 call sites. applySkin dispatches `mms-skin`; the
 * attribute on <html> is the source of truth either way, so a render that
 * happens before the event still reads the right value.
 */
function useSkin(): string {
  return useSyncExternalStore(
    (cb) => {
      window.addEventListener('mms-skin', cb);
      return () => window.removeEventListener('mms-skin', cb);
    },
    () => document.documentElement.dataset.skin ?? 'classic',
    () => 'classic',
  );
}

export function Icon({ name, size = 20, ...rest }: IconProps) {
  const material = useSkin() === 'm3';
  return (
    <svg
      width={size}
      height={size}
      // Material Symbols are drawn on a 960-unit grid with the baseline at 0,
      // and are filled shapes rather than strokes.
      viewBox={material ? '0 -960 960 960' : '0 0 24 24'}
      fill={material ? 'currentColor' : 'none'}
      stroke={material ? 'none' : 'currentColor'}
      strokeWidth={material ? undefined : 2}
      strokeLinecap={material ? undefined : 'round'}
      strokeLinejoin={material ? undefined : 'round'}
      aria-hidden="true"
      {...rest}
    >
      {material ? MATERIAL_PATHS[name] : PATHS[name]}
    </svg>
  );
}

